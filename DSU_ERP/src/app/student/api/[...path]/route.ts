import { NextRequest } from "next/server";
import { backendApi } from "@/shared/http/backend";
import { userSession } from "@/shared/auth/session";
import { CampusError } from "@/shared/http/errors";
import { sameOrigin } from "@/features/placement/lib/request";
import { skillRouteAllowed } from "@/features/student/lib/skills";
export const runtime = "nodejs";
export const dynamic = "force-dynamic";
const json = (body: unknown, status = 200) =>
  Response.json(body, {
    status,
    headers: { "Cache-Control": "private, no-store" },
  });
const ONBOARDING_REQUIRED = {
  code: "ONBOARDING_REQUIRED",
  error: "Complete your skills onboarding first.",
};

async function handle(
  req: NextRequest,
  context: { params: Promise<{ path: string[] }> },
) {
  if (req.method !== "GET" && !sameOrigin(req))
    return json({ error: "Invalid request origin." }, 403);
  try {
    const { path } = await context.params;
    if (
      !path.every(
        (part) =>
          /^[a-zA-Z0-9.-]{1,80}$/.test(part) && part !== "." && part !== "..",
      )
    )
      return json({ error: "Invalid resource." }, 400);
    const skills = path[0] === "skills";
    if (skills && !skillRouteAllowed(req.method, path))
      return json({ error: "Unknown resource." }, 404);
    // Verify the user once and reuse the session for every backend call in
    // this request (the /session check and the resource itself).
    const session = await userSession();
    // While skills onboarding is required only skills resources are served,
    // matching the page gate. /session is read once per request; reads run
    // alongside it and are discarded when the gate applies, writes wait.
    const gate = skills
      ? null
      : backendApi<{ data: { onboardingRequired?: boolean } }>("/session", { session }).then(
          (r) => r.data?.onboardingRequired === true,
        );
    if (gate && req.method !== "GET" && (await gate)) return json(ONBOARDING_REQUIRED, 403);
    let body: string | undefined;
    if (req.method === "POST") {
      const reader = req.body?.getReader();
      if (!reader) return json({ error: "Request is empty." }, 400);
      const chunks: Uint8Array[] = [];
      let size = 0;
      while (true) {
        const { value, done } = await reader.read();
        if (done) break;
        size += value.byteLength;
        if (size > 15 * 1024 * 1024) {
          await reader.cancel();
          return json({ error: "Request exceeds 15 MB." }, 413);
        }
        chunks.push(value);
      }
      body = Buffer.concat(chunks).toString("utf8");
      JSON.parse(body);
    }
    const pending = backendApi(
      // Skills resources take no query parameters.
      `/student/${path.join("/")}${skills ? "" : req.nextUrl.search}`,
      { method: req.method as "GET" | "POST", body,
        // A full plan has a 60 s provider deadline plus authenticated database
        // reads and persistence. Other AI work retains its 75 s transport.
        timeoutMs: req.method === "POST" && path[0] === "interviews" && path.length === 1
          ? 85000
          : (path[0] === "conversations" && path[2] === "message") ||
              (req.method === "POST" && path[0] === "sessions" && ["answer", "evaluate", "coach"].includes(path[2]))
            ? 75000
            // An AI skill summary is generated by the backend's model call.
            : req.method === "POST" && skills && path[1] === "summary" ? 75000 : undefined,
        session,
      },
    );
    if (gate) {
      // The gate decides first: a failed /session read fails closed, and a
      // required onboarding discards whatever the resource returned.
      const [required, result] = await Promise.allSettled([gate, pending]);
      if (required.status === "rejected") throw required.reason;
      if (required.value) return json(ONBOARDING_REQUIRED, 403);
      if (result.status === "rejected") throw result.reason;
      return json(result.value);
    }
    return json(await pending);
  } catch (error) {
    if (process.env.NODE_ENV === "development" && error instanceof CampusError)
      console.warn("Student API request failed", { status: error.status, code: error.code });
    if (error instanceof Error && error.message.includes("NEXT_REDIRECT"))
      return json({ error: "Please sign in again." }, 401);
    return json(
      {
        code: error instanceof CampusError ? error.code : undefined,
        // Only the sanitised extra fields from readCampusResponse.
        details: error instanceof CampusError ? error.details : undefined,
        error:
          error instanceof CampusError
            ? error.message
            : "The request could not be completed.",
      },
      error instanceof CampusError ? error.status : 400,
    );
  }
}
export { handle as GET, handle as POST };
